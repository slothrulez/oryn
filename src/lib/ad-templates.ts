/* ==================== Shareable recipe format (template economy) ==================== */

/**
 * A template is a recipe, and recipes are meant to travel — the ComfyUI/n8n
 * playbook where shareable configs become community currency. This block defines
 * the interchange format: a small JSON envelope around one AdTemplate. Exports
 * strip the id (the importer mints its own); imports are clamped by
 * sanitizeCustomAdTemplate (unknown ids degrade to safe defaults, so a file from
 * a future version with new presets still lands usable) and screened against the
 * ad-law lexicon. Lexicon hits surface as WARNINGS, never rejections: a template
 * is a creative directive, not published copy — guardrail sentences like
 * "never claim therapeutic effects" and aesthetic idioms like "soothing" hit the same terms as real
 * violations (14 of our own curated 391 match), so word-level rejection here is
 * all false positives. The hard gate stays where context is real: the compose
 * stage scans the actual voiceover/captions of the finished video.
 */
export const AD_TEMPLATE_SHARE_KIND = "oryn-ad-template";
export const AD_TEMPLATE_SHARE_VERSION = 1;

export type AdTemplateShareError =
  | "invalid_json"
  | "wrong_kind"
  | "unsupported_version"
  | "invalid_template";

export interface AdTemplateShareResult {
  template?: AdTemplate;
  error?: AdTemplateShareError;
  /** Ad-law lexicon hits in the recipe text — shown to the user, never blocking */
  warnings?: string[];
}

/** Serialize a template as a shareable JSON document (id stripped; pretty-printed for hand editing). */
export function exportAdTemplateShare(template: AdTemplate): string {
  const recipe: Partial<AdTemplate> = { ...template };
  delete recipe.id;
  return JSON.stringify(
    { kind: AD_TEMPLATE_SHARE_KIND, version: AD_TEMPLATE_SHARE_VERSION, template: recipe },
    null,
    2
  );
}

/** Parse + validate + compliance-screen a shared template JSON string. */
export function parseAdTemplateShare(raw: string): AdTemplateShareResult {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return { error: "invalid_json" };
  }
  const envelope = parsed as { kind?: unknown; version?: unknown; template?: unknown } | null;
  if (!envelope || envelope.kind !== AD_TEMPLATE_SHARE_KIND) return { error: "wrong_kind" };
  if (envelope.version !== AD_TEMPLATE_SHARE_VERSION) return { error: "unsupported_version" };
  const template = sanitizeCustomAdTemplate(envelope.template);
  if (!template) return { error: "invalid_template" };
  const warnings = complianceTerms(template);
  return { template, ...(warnings.length > 0 && { warnings }) };
}

/** Ad-law lexicon hits in one template's recipe copy (shared by single + pack parsing). */
function complianceTerms(template: AdTemplate): string[] {
  return checkAdCompliance(
    [template.name.en, template.tagline.en, template.scriptHint.en].join(" \n ")
  ).map((v) => v.term);
}

/* ==================== Multi-template pack ==================== */

export const AD_TEMPLATE_PACK_KIND = "oryn-ad-template-pack";
/** Hard ceiling on pack size — entries past it are dropped (protects the DB from a hostile multi-megabyte file). */
const AD_TEMPLATE_PACK_MAX = 100;

export interface AdTemplatePackResult {
  templates?: AdTemplate[];
  error?: AdTemplateShareError;
  /** Ad-law lexicon hits across ALL entries, deduplicated — shown to the user, never blocking */
  warnings?: string[];
}

/** Serialize several templates as one shareable pack document (ids stripped, like the single format). */
export function exportAdTemplatePack(templates: AdTemplate[]): string {
  const recipes = templates.map((t) => {
    const recipe: Partial<AdTemplate> = { ...t };
    delete recipe.id;
    return recipe;
  });
  return JSON.stringify(
    { kind: AD_TEMPLATE_PACK_KIND, version: AD_TEMPLATE_SHARE_VERSION, templates: recipes },
    null,
    2
  );
}

/**
 * Parse a share document of EITHER kind — one template or a pack — behind the
 * same paste box. Pack entries are clamped individually; entries that are not
 * objects at all are dropped, and the parse fails only when nothing usable
 * remains. Warnings are the union across entries.
 */
export function parseAdTemplateShareAny(raw: string): AdTemplatePackResult {
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return { error: "invalid_json" };
  }
  const envelope = parsed as
    | { kind?: unknown; version?: unknown; template?: unknown; templates?: unknown }
    | null;
  if (!envelope || (envelope.kind !== AD_TEMPLATE_SHARE_KIND && envelope.kind !== AD_TEMPLATE_PACK_KIND)) {
    return { error: "wrong_kind" };
  }
  if (envelope.version !== AD_TEMPLATE_SHARE_VERSION) return { error: "unsupported_version" };
  const entries =
    envelope.kind === AD_TEMPLATE_PACK_KIND
      ? Array.isArray(envelope.templates)
        ? envelope.templates
        : []
      : [envelope.template];
  const templates = entries
    .slice(0, AD_TEMPLATE_PACK_MAX)
    .map((entry) => sanitizeCustomAdTemplate(entry))
    .filter((t): t is AdTemplate => t !== null);
  if (templates.length === 0) return { error: "invalid_template" };
  const warnings = [...new Set(templates.flatMap(complianceTerms))];
  return { templates, ...(warnings.length > 0 && { warnings }) };
}

