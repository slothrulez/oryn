/**
 * Clamp an LLM-produced template object into a guaranteed-valid AdTemplate.
 * Every field is validated against the real preset vocabularies; anything invalid
 * falls back to a safe default instead of failing — the LLM's creative intent
 * survives where it was legal, and the pipeline never receives an unknown id.
 * Returns null only when the input is not an object at all.
 */
export function sanitizeCustomAdTemplate(raw: unknown): AdTemplate | null {
  if (!raw || typeof raw !== "object") return null;
  const r = raw as Record<string, unknown>;
  const str = (v: unknown, max = 120): string => (typeof v === "string" ? v.trim().slice(0, max) : "");
  const nameRaw = (r.name ?? {}) as Record<string, unknown>;
  const taglineRaw = (r.tagline ?? {}) as Record<string, unknown>;
  const hintRaw = (r.scriptHint ?? {}) as Record<string, unknown>;
  const nameEn = str(nameRaw.en, 48) || "AI Custom";

  const videoMode = (VIDEO_MODES.has(String(r.videoMode)) ? String(r.videoMode) : "product_closeup") as AdTemplate["videoMode"];
  const groupRaw = String(r.group ?? "");
  const group = (AD_TEMPLATE_GROUPS.some((g) => g.id === groupRaw) ? groupRaw : GROUP_BY_MODE[videoMode]) as AdTemplateGroupId;

  const cameraPlan: Partial<Record<Shot["type"], string>> = {};
  if (r.cameraPlan && typeof r.cameraPlan === "object") {
    for (const [type, presetId] of Object.entries(r.cameraPlan as Record<string, unknown>)) {
      if (SHOT_TYPES.has(type) && typeof presetId === "string" && getCameraPreset(presetId)) {
        cameraPlan[type as Shot["type"]] = presetId;
      }
    }
  }
  if (Object.keys(cameraPlan).length < 2) {
    Object.assign(cameraPlan, { hook: "crash_push", product_reveal: "orbit_slow", demo: "macro_glide", cta: "push_then_hold" });
  }

  const composeRaw = (r.compose ?? {}) as Record<string, unknown>;
  const compose: StylePackCompose = {
    captionPreset: isCaptionPreset(composeRaw.captionPreset) ? composeRaw.captionPreset : "standard",
    bgm: BGM_VALUES.has(String(composeRaw.bgm)) ? (String(composeRaw.bgm) as StylePackCompose["bgm"]) : "upbeat",
    bgmDuck: typeof composeRaw.bgmDuck === "boolean" ? composeRaw.bgmDuck : true,
    ...(QUALITY_VALUES.has(String(composeRaw.quality)) && { quality: String(composeRaw.quality) as StylePackCompose["quality"] }),
    ...(typeof composeRaw.productCard === "boolean" && { productCard: composeRaw.productCard }),
  };

  const goodFor = Array.isArray(r.goodFor)
    ? (r.goodFor.filter((c) => ["beauty", "food", "home", "fashion", "digital"].includes(String(c))) as AdTemplateCategory[])
    : [];

  return {
    id: CUSTOM_AD_TEMPLATE_ID,
    emoji: str(r.emoji, 8) || "✨",
    name: { en: nameEn },
    tagline: {
      en: str(taglineRaw.en, 120) || "An AI-tailored recipe for this product",
    },
    group,
    ...(goodFor.length > 0 && { goodFor }),
    styleType: STYLE_VALUES.has(String(r.styleType)) ? String(r.styleType) : "pain-point",
    videoMode,
    look: getLookPreset(str(r.look)) ? str(r.look) : "daylight_clean",
    cameraPlan,
    compose,
    scriptHint: { en: str(hintRaw.en, 300) || "Build around the product's core selling points with a tight pace; visuals and voiceover complement each other" },
  };
}

/** Stored-value prefix marking an inline custom template (vs. a builtin id). */
const CUSTOM_STORED_PREFIX = "custom:";

/**
 * Encode a template selection for localStorage: builtin → its id, everything else
 * (AI custom AND user-owned "my templates") → inline JSON. Deciding by library
 * lookup instead of the custom-id sentinel matters: a my-template id stored bare
 * would be unresolvable on decode (it only exists in the DB, not in this module).
 */
export function encodeStoredAdTemplate(template: AdTemplate): string {
  return getAdTemplate(template.id)
    ? template.id
    : CUSTOM_STORED_PREFIX + JSON.stringify(template);
}

/** Decode a stored selection back to a template (builtin lookup or sanitized inline custom). */
export function decodeStoredAdTemplate(raw: string | null | undefined): AdTemplate | undefined {
  if (!raw) return undefined;
  if (raw.startsWith(CUSTOM_STORED_PREFIX)) {
    try {
      return sanitizeCustomAdTemplate(JSON.parse(raw.slice(CUSTOM_STORED_PREFIX.length))) ?? undefined;
    } catch {
      return undefined;
    }
  }
  return getAdTemplate(raw);
}

